/**
 * 止められている最中かどうか。
 *
 * ArgoCD の同期やイメージの入れ替えで Pod が差し替わるとき、録画中でも
 * 容赦なく止められる。TSは追記で開いているので**次の起動で続きから録れる**が、
 * 入れ替わるまでの十数秒は落ちる。そこを落としたくないので、
 * SIGTERM を受けても**録画が終わるまで居座る** (runtime.ts)。
 *
 * **居座っている間も、始まる録画は始める。** 始めないでいた頃は、
 * 居座りの間に始まる番組の頭が丸ごと落ちていた (`scheduler.ts` に実測)。
 * 始めればそのぶん居座りが伸びるが、`SHUTDOWN_WAIT` が歯止めになっている。
 *
 * つまりこの印は**もう止めるためには使っていない**。残してあるのは、
 * 記録に「止まる途中で始めた」と書くため — 外から見て、なぜ入れ替えが
 * 降りてこないのかが読めるようにしておく。
 *
 * 小さな別モジュールにしてあるのは、runtime と scheduler の両方から
 * 見たいため (同じファイルに置くと読み込みが輪になる)。
 */

let draining = false;

export function beginDraining(): void {
    draining = true;
}

export function isDraining(): boolean {
    return draining;
}
