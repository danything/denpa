        padding: 1rem 0.375rem 0.375rem;
    }
    /*
     * **操作バーを映像の下に出す (スマホの縦。舞台の `data-under`)。** 格子の下の段に置き、
     * 敷きもの (ぼかし) は外す — 映像に重ならないので要らない。**いつも出しておく** —
     * 映像を覆わないので、引っ込めても見えるものが増えない。触るたびに出し直す手間が残るだけ
