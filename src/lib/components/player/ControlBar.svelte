        padding: 0.5rem;
    }
    /*
     * **右上の丸は 40px** (下の操作バーは 48px)。観る流れの外のものなので、映像の角で重く見せない。
     * 指で押す的の 40px は割らない (狭い枠の大きさと同じ)
