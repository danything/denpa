<script lang="ts">
  /**
     * 映像に重ねる操作列。**3画面 (ライブ・追っかけ・観る画面) で同じもの。**
     *
     * - **黒いぼかしの上に置く。** 明るい映像の上でも読めるように
     * - **しばらく触らなければ消える** (`shown`)。映像の上に居座るものなので、
     *   見ている間は引っ込んでいるほうがいい
     * - 消えている間は押せなくする (`pointer-events: none`)。見えないものが
     *   押されると、映像を押したつもりが操作に取られる
     *
     * 下端 (既定) と右端 (`side`) の2つ。**下は観ながら使うもの、右端は観る流れの
     * 外にあるもの** — 閉じる・録画・切り抜く・消すは、並べる理由も押す頻度も
     * 他と違う。1列に混ぜていた頃は、押すものが12個並んで**名前が入る幅が
     * 残らなかった**。
     *
     * 中身は画面ごとに違う。下は「ライブはライブへ戻る・Hybridcast、観る画面は送りとチャプター」、
     * 右端は上から「観る画面は閉じる・切り抜き・削除、ライブは録画・d・切り抜き、追っかけは閉じる・切り抜き」。
     * いちばん上 (角) はその画面だけのもの (閉じる・録画)。
     *
     * **右端は縦に積み、丸は大きいまま (48px)。横に寝かせない・縮めない。** 車に付けたタブレットでは、
     * 映像の右の縁を縦になぞる指がいちばん届きやすい。タブレットでは全画面で観るので、**閉じる・切り抜き・
     * 削除は映像の上に置き、全画面から出ずに押せるようにする** (観る画面のデータ放送 d は ⚙ の中へ出して
     * 列を短くした)。横一行・40px・削除を右の列へ、と一度変えて戻した — 横持ちでは上下の操作バーの間に
     * 挟まって窮屈で、小さい丸は車の中で押しにくく、削除は全画面のままでは届かなかった

     *
     * ## 読みものは押すものの間に、二段で
     *
     * 下の操作バーの中身は「シークバーの行」と「押すものの行」の二段。**読みもの
     * (時刻・局名・番組名・遅れ) は独立した行を作らず、押すものの行の空きに
     * 入れる** — 行を足すとそのぶん操作バーが高くなって映像に掛かる。文字2行 (36px) は
     * 押すもの (48px) より低いので、二段にしても操作バーは厚くならない。
     *
     * 守ることが2つ。**どの画面でも同じ**:
     *
     * - **幅ゼロから伸ばす** (`min-width: 0; flex: 1 1 0`)。押すものと同じに中身の幅で
     *   並べていた頃は、**名前が長いだけで操作バーが二段に折れて**いた (実機のタブレット) —
     *   折り返すかどうかは中身の幅で決まるので、縮む指定 (`text-overflow: ellipsis`) より先に
     *   行が分かれてしまう
     * - **並びは時刻・局名・番組名。縮むのは番組名だけ**。時刻と局名は幅が
     *   知れているので先に確保し、余りを名前にやって、入らないぶんだけ省く。
     *   名前を先に置いていた頃は、長い名前に押し出されて他が見えなくなっていた
     *
     * ## 横の列は、映像に 476px 残るところまで
     *
     * **操作バーが折れるかどうかは、映像に残る幅で決まる。** 縦の iPad (820px) で右の列に
     * 320px を先に取ると**映像が 436px しか残らず**、48px の押しもの9個が並びきらずに
     * 操作バーが二段になる。二段組にした直後は 256px にして 476px 残し、
     * 広い画面 (1024px から) で 320px に戻す。**どの画面でも同じ** — 読むものは
     * 細くても読めるが、映像は狭いと見られない
     *
     * ## 狭い枠・低い枠では詰める
     *
     * 枠の大きさは舞台 (`PlayerStage`) が測って `data-compact` に出す。
     * **狭い枠 (スマホの縦) では操作バーの余白も削る** — 映像が 224px しか無いところで
     * 上に 32px のぼかしを取ると、操作バーだけで映像の半分になっていた。
     * スマホの縦でも操作バーは映像に重ね、触らなければ引っ込める (以前は映像の下に段を足して出しっぱなしに
     * していた。理由と今の形は `PlayerStage` の `narrow`)
     */
  let {
    shown = true,
    side = false,
    testid,
    children,
  }: {
    shown?: boolean;
    side?: boolean;
    testid?: string;
    children: import("svelte").Snippet;
  } = $props();

  /**
   * **敷くのは下端だけ。**
   *
   * 下は映像の幅いっぱいに渡るので、まっすぐ上へ流せば端が出ない。文字 (時刻・
   * 番組名) を載せるのもこちらなので、明るい映像の上でも読めるように要る。
   *
   * **右端には敷かない。** 載っているのは丸いボタンだけで、そのひとつずつが
   * 既に黒く敷いてある (`OVERLAY`)。全体にも敷くと、映像の上に**四角い影が
   * 貼り付いて**見える — 直線のぼかしは色の変わり目が一方向にしか進まない
   * ので、横へ流せば下端が、斜めへ流せば左端と下端が直線で切れる。
   * 角から丸く散らす手もあるが、要らないものを丁寧に薄くしているだけだった
   */
</script>

<div
  class="bar"
  class:side
  class:bottom={!side}
  class:away={!shown}
  data-testid={testid}
  data-shown={shown}
  data-stage-bar={side ? undefined : ""}
>
  {@render children()}
</div>

