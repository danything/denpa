/**
 * ライブの再生位置の決め方。**放送は待ってくれないが、目は待てる。**
 *
 * 届いた端でそのまま再生すると、1コマ遅れるたびに映像が止まる。ネットワークも
 * エンコードも一定では届かないので、これは常時起きる。少しだけ貯めてから出し、
 * 離れたら少し速く再生して詰める。跳ぶのは大きく離れたときだけ — 跳ぶと
 * 音が切れるので、常用すると「かくつき」そのものになる。
 *
 * **どれだけ貯めるかは動かす。** 宅内なら 0.2 秒 (`FLOOR`) で足りるが、宅外から
 * 見ると届き方が荒れて止まる。止まったら伸ばし、しばらく無事なら縮める
 * (`nextTarget`)。初めに大きく取ると、開いてから絵が出るまでが遅くなる。
 *
 * DOM を触らないので、ここだけ単体で確かめられる。
 */

/**
 * 貯める量の下限。**開いた直後はここから始める。**
 *
 * **そのぶん絵が出るのが遅くなる。** 再生を始める条件は「貯まった尺 ≧ これ」
 * (`pacing` の `play`) で、電波は実時間で届くのだから、0.2 秒貯めるには
 * 0.2 秒かかる。**開いてから絵が出るまでの内訳で、いちばん大きい削り代**
 * ([stream.md](../../../docs/stream.md) §4) — 電波のロックも ffmpeg の
 * 立ち上がりもこちらの都合では動かないが、ここは動かせる。
 *
 * **0.2 秒 = 塊4つぶん。** サーバは 0.05 秒ずつ塊を出すので
 * (`server/live.ts` の `-frag_duration`)、4つ貯めてから始めることになる。
 *
 * **小さすぎても壊れない。** 足りずに止まったら 0.6 ずつ増える (`nextTarget`)
 * ので、宅外のように荒れる経路では自分で伸びていく。戻るほうは割合で
 * (`SHRINK_RATIO`) — 迷ったら小さいほうから始める
 */
export const FLOOR = 0.2;
/** 貯める量の上限。これ以上は、遅れが目に見えて増えるだけ */
export const CEILING = 6;
/** 止まったときに増やす量 */
const GROW = 0.6;
/**
 * 無事だったときに減らす割合。**大きく膨らんだぶんほど速く戻す。**
 *
 * 0.15 秒ずつの決め打ちにしていた頃は、**一度増えた遅れが減っていかない**
 * ように見えた (実機)。1.4 秒まで伸びると 0.2 へ戻るのに 8回 = 40秒かかり、
 * その間にもう一度止まれば振り出しに戻る — 止まりがちな経路では、
 * 事実上ずっと増えっぱなしになる。
 *
 * 割合で減らすと、膨らんだ直後がいちばん大きく戻る (1.4 なら 1回目で 0.28)。
 * 小さいところでは下の `SHRINK_LEAST` が効いて、じわりと詰める
 */
const SHRINK_RATIO = 0.2;
/** 1回で減らす量の下限 (秒)。割合だけだと、小さいところで止まってしまう */
const SHRINK_LEAST = 0.1;
/**
 * これだけ無事なら縮めにかかる (秒)。
 *
 * **戻りが遅すぎると「直っていない」に見える。** 45秒にしていた頃は元に
 * 戻るのに3分かかっていた。30秒でもまだ長い — 止まる間隔のほうが短いと、
 * 縮めにかかる前に次の1回が来て伸びる
 */
export const SETTLED = 15;

/** これ以上離れたら跳ぶ。別のタブへ行って戻ってきたとき */
export const JUMP = 8;
/** 詰めるときの速さ。上げすぎると音程が分かるほど狂う */
const CATCH_UP = 1.05;

export interface Buffered {
    /** 持っている中でいちばん古い時刻 */
    start: number;
    /** いちばん新しい時刻 = 放送の今 */
    end: number;
    /** いま再生している時刻 */
    at: number;
    /** もう再生を始めているか */
    playing: boolean;
    /** どれだけ貯めてから出すか */
    target: number;
    /**
     * 追っかけ再生か。**放送の今を追わない。**
     *
     * 止めて見ていたり、帯を戻したりして**わざと遅れて見ている**状態。
     * ここで勝手に跳ぶと、見ようとしていた場面を飛ばすことになる
     */
    chasing: boolean;
    /** 追っかけ中の速さ。見ている人が選ぶ。ライブに戻れば使わない */
    speed: number;
}

export interface Pacing {
    /** ここへ移る。移らないなら null */
    seek: number | null;
    /** ここで再生を始める */
    play: boolean;
    /** 再生の速さ。**null は今のまま** (毎回入れ直すと往復する) */
    rate: number | null;
    /** 追っかけが放送の今に追いついた。**呼ぶ側はライブに戻す** */
    caught: boolean;
}

/**
 * 次にどうするかを決める。
 *
 * **頭出しは自分で合わせる。** `-copyts` で放送の時刻をそのまま持っているので、
 * 持っている範囲は 0 秒から始まらない (数万秒のこともある)。何もしないと
 * 再生位置が範囲の外に居るままで、1コマも出ない。
 *
 * ## 追っかけ中は跳ばない
 *
 * 追っかけかどうかで**別のものを見ている**。ライブは「放送の今」を追うので、
 * 大きく離れたら跳んで詰めるのが正しい (別のタブから戻ってきたとき)。
 * 追っかけは**わざと遅れて見ている**ので、跳ぶと見ようとしていた場面が飛ぶ。
 *
 * 分けていなかった頃は、**止めて再開すると勝手に放送の今へ跳んで**いた —
 * 「止めた所から見られる」と謳っておきながら、8秒より長く止めると戻れなかった。
 */
export function pacing({ start, end, at, playing, target, chasing, speed }: Buffered): Pacing {
    // 範囲の外に居る。チャンネルを変えた直後もここを通る
    if (at < start || at > end) return { seek: start, play: false, rate: 1, caught: false };

    // まだ貯まっていない。始めると、すぐ足りなくなって止まる
    if (!playing) return { seek: null, play: end - at >= target, rate: 1, caught: false };

    const lag = end - at;

    if (chasing) {
        /*
         * **追いついた。** ここから先はライブと同じ扱いにする — 選んだ速さのまま
         * だと放送を追い越してしまい、溜まりを使い切って止まる
         */
        if (lag <= target * 1.1) return { seek: null, play: true, rate: 1, caught: true };
        // 跳ばない。選ばれた速さのまま進む
        return { seek: null, play: true, rate: speed, caught: false };
    }

    // 大きく離れた。**詰めきれないので跳ぶ** — 別のタブから戻ってきたとき
    if (lag > target + JUMP) return { seek: end - target, play: true, rate: 1, caught: false };
    /*
     * 少し離れた。速めて詰める。跳ばないので音は切れない。
     *
     * **帯を狭く採る。** 2.5倍まで放っておいた頃は、実機で 0.4 秒を狙って
     * 0.70 秒に居着いていた — 始めた直後は必ず狙いより溜まる (再生を頼んでから
     * 実際に絵が出るまでの間にも届く) ので、放っておくとそこから下りてこない。
     */
    if (lag > target * 1.5) return { seek: null, play: true, rate: CATCH_UP, caught: false };
    // 追いついた。戻す。**溜まりを使い切る前に戻す**ので、少し余裕を残す
    if (lag <= target * 1.1) return { seek: null, play: true, rate: 1, caught: false };
    // その間。速さは今のまま (ここで戻すと、速める・戻すを往復する)
    return { seek: null, play: true, rate: null, caught: false };
}

/**
 * 追っかけで選べる速さ。**遅くは出さない。**
 *
 * 追っかけは「放送に追いつきたい」ための機能なので、1倍より遅い選択肢は
 * 目的と逆を向く。上は2倍まで — それ以上は音が聞き取れなくなる
 */
export const SPEEDS = [1, 1.25, 1.5, 2] as const;

/**
 * 貯める量を決め直す。**止まったら伸ばし、無事が続いたら縮める。**
 *
 * 宅内と宅外で必要な量が桁違いに違うのに、どちらから見ているかは分からない。
 * 決め打ちにすると、宅内に合わせれば宅外で止まり、宅外に合わせれば宅内が
 * 無駄に遅れる。**実際に止まったかどうかで決める**のがいちばん確か。
 *
 * 伸ばすのは一気に、戻すのは割合で。**膨らんだぶんほど速く戻る** —
 * 決め打ちで 0.15 ずつ戻していた頃は、一度増えた遅れが減っていかないように
 * 見えた (1.4 秒から 0.2 秒まで 40秒。その間にもう一度止まれば振り出し)。
 *
 * @param target いまの量
 * @param stalled 前回からこちら、詰まったか
 * @param settledFor 最後に詰まってから経った秒数
 */
export function nextTarget(target: number, stalled: boolean, settledFor: number): number {
    if (stalled) return Math.min(CEILING, target + GROW);
    if (settledFor < SETTLED) return target;
    return Math.max(FLOOR, target - Math.max(SHRINK_LEAST, target * SHRINK_RATIO));
}
