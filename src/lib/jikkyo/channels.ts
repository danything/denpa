/** 名前と当てるチャンネル。長い名前から並べる */
const NAMES: readonly (readonly [string, string])[] = Object.entries(
  TERRESTRIAL,
)
  .flatMap(([channel, names]) => names.map((name) => [name, channel] as const))
  .sort((a, b) => b[0].length - a[0].length);

