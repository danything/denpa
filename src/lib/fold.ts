/** 異体字セレクタ (VS15/VS16)。絵文字か文字かの指定で、探すときは意味を持たない */
const SELECTOR = /[\uFE0E\uFE0F]/gu;

/** 寄せる字。1 文字ずつ見る (𠮷 は 2 単位なので、文字単位で回す) */
const KEYS = new RegExp(`[${[...FOLD.keys()].join("")}]`, "gu");

/** 探す前に通す。大文字小文字・全角半角は呼ぶ側が揃える */
export function foldForSearch(text: string): string {
  return text.replace(SELECTOR, "").replace(KEYS, (c) => FOLD.get(c) ?? c);
}

/**
 * **全角の英数・記号と全角の空白を半角に寄せる。** 比べるとき・ファイル名にするときに通す。
 *
 * 番組表は放送のとおり全角混じりで持つ (`packages/arib/src/aribtext.ts`)。人が打つのは半角なので、
 * 探す・比べる側で揃える。**1 文字を 1 文字に写す** (UTF-16 の長さが変わらない) ので、
 * 寄せた写しで探した位置で元の文字列を切れる (`server/title.parseTitle`)
 */
export function toHalfWidth(input: string): string {
  return input
    .replace(/[！-～]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/　/g, " ");
}

/** 寄せ先の文字列 (小文字)。SQL に掛けられない所を探すのに使う */
const OUTPUTS = [
  ...new Set([...FOLD.values()].map((v) => [...v.toLowerCase()])),
];

/**
 * **SQL の前絞りに掛けてよい切れ端。** 語は寄せて小文字にしたもの。
 *
 * DB には規格の字のまま入っているので、寄せた語を丸ごと掛けると
 * 「吉野家」が「𠮷野家」を落とす。そこで寄せ先の字に重なりうる所を抜き、残りの切れ端を返す。
 * 重なりうる所は、寄せ先がまるごと入っている所と、語の端が寄せ先の途中で切れている所 (「新」は「[新]」の中)。
 * 切れ端は**全部含むはず**なので AND で掛けられる。
 * 何も残らなければ空 (その語では絞れない)
 */
export function likePieces(word: string): string[] {
  const chars = [...word];
  const touched = chars.map(() => false);
  for (const out of OUTPUTS) {
    // 寄せ先を語にずらして重ね、重なった所が一致すればそこは寄せ先かもしれない
    for (let shift = 1 - out.length; shift < chars.length; shift++) {
      const from = Math.max(0, shift);
      const to = Math.min(chars.length, shift + out.length);
      let same = true;
      for (let i = from; i < to && same; i++)
        same = chars[i] === out[i - shift];
      if (same) touched.fill(true, from, to);
    }
  }
  const pieces: string[] = [];
  let run = "";
  chars.forEach((c, i) => {
    if (touched[i]) {
      if (run !== "") pieces.push(run);
      run = "";
    } else run += c;
  });
  if (run !== "") pieces.push(run);
  return pieces;
}

/**
 * 半角の 1 字を、全角・大文字も当たる GLOB の字の組にする (`a` → `[ａＡaA]`)。
 * `]` は組の先頭でしか字にならず、`^` は先頭だと否定、`-` は間だと範囲になるので、
 * 全角を先・半角を後に並べる (`]` だけは半角を先頭に)
 */
function globChar(ch: string): string {
  if (ch < "!" || ch > "~") return ch;
  const wide = (c: string) => String.fromCharCode(c.charCodeAt(0) + 0xfee0);
  if (ch === "]") return `[]${wide(ch)}]`;
  const upper = ch.toUpperCase();
  return upper === ch
    ? `[${wide(ch)}${ch}]`
    : `[${wide(ch)}${wide(upper)}${ch}${upper}]`;
}

/**
 * 寄せて小文字にした語 (`server/title.searchable`) を SQL の `GLOB` のパターン (`*切れ端*`) にする。
 * どれも**必ず含むはず**のものなので AND で掛けられる。
 *
 * **LIKE ではなく GLOB。** DB の番組名は放送のとおり全角混じり (「Ｖｅｎｕｅ１０１」) で、
 * 語は半角に寄せてある。GLOB なら英数・記号の 1 字ごとに全角と大文字を並べた組
 * (`[ｖＶvV]`) で当てられる。大文字小文字も組で揃えるので、組を作れない
 * 大文字小文字を持つ非 ASCII の字 (キリル文字など) を含む切れ端と、絞れない語は何も返さない
 */
export function globTerms(words: string[]): string[] {
  return words
    .flatMap(likePieces)
    .filter((piece) =>
      [...piece].every(
        (ch) => /[a-z0-9]/.test(ch) || ch.toLowerCase() === ch.toUpperCase(),
      ),
    )
    .map((piece) => `*${[...piece].map(globChar).join("")}*`);
}
